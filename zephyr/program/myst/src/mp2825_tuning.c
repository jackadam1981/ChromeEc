static void mp2825_on_startup(void)
{
	static int chip_updated;
	int status;

	if (chip_updated)
		return;

	chip_updated = 1;

	ccprintf("%s: attempting to tune PMIC\n", __func__);
	status = mp2825_tune(rail_a, ARRAY_SIZE(rail_a),
			     rail_b, ARRAY_SIZE(rail_b),
			     rail_c, ARRAY_SIZE(rail_c));
	ccprintf("%s: PMIC update done\n", __func__);

	if (status != EC_SUCCESS)
		ccprintf("%s: could not update all settings\n", __func__);
}
DECLARE_HOOK(HOOK_CHIPSET_STARTUP, mp2825_on_startup, HOOK_PRIO_FIRST);
