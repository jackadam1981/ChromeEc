{
	uint8_t i, j, val;

	if (imvp_check_nvm_status(7, 1) == EC_SUCCESS) {
		if (imvp_check_id() != EC_SUCCESS) {
			CPRINTF("Fault 2");
			return EC_ERROR_UNKNOWN;
		}
		if (imvp_check_fw_version() != EC_SUCCESS ||
		    imvp_check_crc() != EC_SUCCESS) {
		step7:
			imvp_write_data();

			for (i = 0; i < 2; i++) {
				imvp_read(0xEC, &val);
				if (val == 0xE0) {
					for (j = 0; j < 4; j++) {
						if (imvp_check_fw_version() ==
							    EC_SUCCESS &&
						    imvp_check_crc() ==
							    EC_SUCCESS) {
							imvp_write(0xF1, 0xFF);
							CPRINTF("IMVP f/w update SUCCESS\n");
							return EC_SUCCESS;
						} else {
							goto step7;
						}
					}
				}
				if (i < 2) {
					k_msleep(1);
				}
				CPRINTF("Fault 4");
				return EC_ERROR_UNKNOWN;
			}

		} else {
			CPRINTF("IMVP f/w update SUCCESS\n");
			return EC_SUCCESS;
		}
	}
	CPRINTF("Fault 1\n");
	return EC_ERROR_UNKNOWN;
}
