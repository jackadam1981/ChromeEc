static void imvp_unlock_nvm(void)
{
	// Unlock NVM
	imvp_write(0xF1, 0x24);
	imvp_write(0xF1, 0x54);
	imvp_write(0xF1, 0x02);
}

// step7~13
static void imvp_write_data(void)
{
	int i;
	imvp_unlock_nvm();
	// Write all dat from page 08 to page 0E
	for (i = 0; i < ARRAY_SIZE(imvp_update_write_data_sit_test); i++) {
		imvp_write(imvp_update_write_data_sit_test[i].reg,
			   imvp_update_write_data_sit_test[i].data);
	}

	// step 9:Store Data into NVM
	imvp_write(0xED, 0xAA);
	for (int i = 0; i < 17; i++) { // 17 * 50ms = 850ms
		k_msleep(50);
	}
	if (imvp_check_nvm_status(6, 20) == EC_SUCCESS) {
		// Reload data from NVM
		imvp_write(0xED, 0x66);
		k_usleep(500);
	}
}

