static int imvp_write(uint8_t reg, uint8_t val)
{
	int rv;
	int data = val;

	rv = i2c_write8(I2C_PORT_IMVP, I2C_ADDR_IMVP, reg, data);

	CPRINTF("writing reg=0x%x val=0x%x, rv=%d\n", reg, val, rv);
	return rv;
}

static int imvp_read(uint8_t reg, uint8_t *val)
{
	int rv;
	int data = 0;

	rv = i2c_read8(I2C_PORT_IMVP, I2C_ADDR_IMVP, reg, &data);

	*val = (uint8_t)data;
	CPRINTF("Read reg=0x%x val=0x%x, rv=%d\n", reg, *val, rv);
	return rv;
}

static int imvp_check_nvm_status(int bit, int retry)
{
	uint8_t val;
	int i;
	for (i = 0; i <= retry; i++) {
		if (imvp_read(0xEC, &val) != 0)
			continue;
		if ((val >> bit) & 0x01)
			return EC_SUCCESS;
		if (i < retry)
			k_msleep(1);
	}
	return EC_ERROR_UNKNOWN;
}

static int imvp_check_nvm_status_0xe0(void)
{
	int i;
	uint8_t val;
	imvp_read(0xEC, &val);
	for (i = 0; i < 2; i++) {
		if (val == 0xE0) {
			return EC_SUCCESS;
		}
		k_msleep(1);
	}
	CPRINTF("Fault 4");
	return EC_ERROR_UNKNOWN;
}

static int imvp_check_id(void)
{
	uint8_t pid, cid, rid;

	imvp_read(0xFE, &pid);
	imvp_read(0xFA, &cid);
	imvp_read(0xE0, &rid);

	if (pid != 0x45 || cid != 0x00 || rid != 0x01) {
		CPRINTF("Fault 2 PID=0x%02x, CID=0x%02x, RID=0x%02x\n", pid,
			cid, rid);
		return EC_ERROR_UNKNOWN;
	}
	return EC_SUCCESS;
}

static int imvp_check_crc(void)
{
	uint8_t crc0, crc1, crc2;

	// Check CRC0
	imvp_write(0xEF, 0x02);
	imvp_read(0x17, &crc0);
	if (crc0 != 0xD1) {
		CPRINTF("IMVP CRC0 mismatch! CRC0=0x%02x\n", crc0);
		return EC_ERROR_UNKNOWN;
	}
	CPRINTF("IMVP CRC0 reg 0x17 = 0x%02x\n", crc0);

	// Check CRC1
	imvp_write(0xEF, 0x08);
	imvp_read(0x0A, &crc1);
	if (crc1 != 0xD1) {
		CPRINTF("IMVP CRC1 mismatch! CRC0=0x%02x\n", crc1);
		return EC_ERROR_UNKNOWN;
	}
	CPRINTF("IMVP CRC1 reg 0x0A = 0x%02x\n", crc1);

	// Check CRC2
	imvp_write(0xEF, 0x0E);
	imvp_read(0x0F, &crc2);
	if (crc2 != 0xBB) {
		CPRINTF("IMVP CRC1 mismatch! CRC0=0x%02x\n", crc2);
		return EC_ERROR_UNKNOWN;
	}
	CPRINTF("IMVP CRC2 reg 0x0F = 0x%02x\n", crc2);

	return EC_SUCCESS;
}

