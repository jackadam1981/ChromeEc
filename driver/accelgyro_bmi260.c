static int get_offset(const struct motion_sensor_t *s,
			int16_t    *offset,
			int16_t    *temp)
{
	int i, val = 0, val98 = 0;
	intv3_t v;

	switch (s->type) {
	case MOTIONSENSE_TYPE_ACCEL:
		/*
		 * The offset of the accelerometer off_acc_[xyz] is a 8 bit
		 * two-complement number in units of 3.9 mg independent of the
		 * range selected for the accelerometer.
		 */
		for (i = X; i <= Z; i++) {
			raw_read8(s->port, s->i2c_spi_addr_flags,
				  BMI260_OFFSET_ACC70 + i, &val);
			if (val > 0x7f)
				val = -256 + val;
			v[i] = round_divide(
				(int64_t)val * BMI260_OFFSET_ACC_MULTI_MG,
				BMI260_OFFSET_ACC_DIV_MG);

		}
		break;
	case MOTIONSENSE_TYPE_GYRO:
		/* Read the MSB first */
		raw_read8(s->port, s->i2c_spi_addr_flags,
			  BMI260_OFFSET_EN_GYR98, &val98);
		/*
		 * The offset of the gyroscope off_gyr_[xyz] is a 10 bit
		 * two-complement number in units of 0.061 °/s.
		 * Therefore a maximum range that can be compensated is
		 * -31.25 °/s to +31.25 °/s
		 */
		for (i = X; i <= Z; i++) {
			raw_read8(s->port, s->i2c_spi_addr_flags,
				  BMI260_OFFSET_GYR70 + i, &val);
			val |= ((val98 >> (2 * i)) & 0x3) << 8;
			if (val > 0x1ff)
				val = -1024 + val;
			v[i] = round_divide(
				(int64_t)val * BMI260_OFFSET_GYRO_MULTI_MDS,
				BMI260_OFFSET_GYRO_DIV_MDS);
		}
		break;
#ifdef CONFIG_MAG_BMI260_BMM150
	case MOTIONSENSE_TYPE_MAG:
		bmm150_get_offset(s, v);
		break;
#endif /* defined(CONFIG_MAG_BMI260_BMM150) */
	default:
		for (i = X; i <= Z; i++)
			v[i] = 0;
	}
	rotate(v, *s->rot_standard_ref, v);
	offset[X] = v[X];
	offset[Y] = v[Y];
	offset[Z] = v[Z];
	/* Saving temperature at calibration not supported yet */
	*temp = EC_MOTION_SENSE_INVALID_CALIB_TEMP;
	return EC_SUCCESS;
}

static int set_offset(const struct motion_sensor_t *s,
			const int16_t *offset,
			int16_t    temp)
{
	int ret, i, val, val98, val_nv_conf;
	intv3_t v = { offset[X], offset[Y], offset[Z] };

	rotate_inv(v, *s->rot_standard_ref, v);

	ret = raw_read8(s->port, s->i2c_spi_addr_flags,
			BMI260_OFFSET_EN_GYR98, &val98);
	if (ret != 0)
		return ret;
	ret = raw_read8(s->port, s->i2c_spi_addr_flags,
			BMI260_NV_CONF, &val_nv_conf);
	if (ret != 0)
		return ret;

	switch (s->type) {
	case MOTIONSENSE_TYPE_ACCEL:
		for (i = X; i <= Z; i++) {
			val = round_divide(
				(int64_t)v[i] * BMI260_OFFSET_ACC_DIV_MG,
				BMI260_OFFSET_ACC_MULTI_MG);
			if (val > 127)
				val = 127;
			if (val < -128)
				val = -128;
			if (val < 0)
				val = 256 + val;
			raw_write8(s->port, s->i2c_spi_addr_flags,
				   BMI260_OFFSET_ACC70 + i, val);
		}
		ret = raw_write8(s->port, s->i2c_spi_addr_flags,
				 BMI260_NV_CONF,
				 val_nv_conf | BMI260_ACC_OFFSET_EN);
		break;
	case MOTIONSENSE_TYPE_GYRO:
		for (i = X; i <= Z; i++) {
			val = round_divide(
				(int64_t)v[i] * BMI260_OFFSET_GYRO_DIV_MDS,
				BMI260_OFFSET_GYRO_MULTI_MDS);
			if (val > 511)
				val = 511;
			if (val < -512)
				val = -512;
			if (val < 0)
				val = 1024 + val;
			raw_write8(s->port, s->i2c_spi_addr_flags,
				   BMI260_OFFSET_GYR70 + i, val & 0xFF);
			val98 &= ~(0x3 << (2 * i));
			val98 |= (val >> 8) << (2 * i);
		}
		ret = raw_write8(s->port, s->i2c_spi_addr_flags,
				 BMI260_OFFSET_EN_GYR98,
				 val98 | BMI260_OFFSET_GYRO_EN);
		break;
#ifdef CONFIG_MAG_BMI260_BMM150
	case MOTIONSENSE_TYPE_MAG:
		ret = bmm150_set_offset(s, v);
		break;
#endif /* defined(CONFIG_MAG_BMI260) */
	default:
		ret = EC_RES_INVALID_PARAM;
	}
	return ret;
}

