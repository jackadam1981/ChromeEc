static int set_data_rate(const struct motion_sensor_t *s,
				int rate,
				int rnd)
{
	int ret, val, normalized_rate;
	uint8_t ctrl_reg, reg_val;
	struct accelgyro_saved_data_t *data = BMI260_GET_SAVED_DATA(s);
#ifdef CONFIG_MAG_BMI260_BMM150
	struct mag_cal_t              *moc = BMM150_CAL(s);
#endif
	CPRINTS("set_data_rate(s, %d, %d)", rate, rnd);
	if (rate == 0) {
		/* FIFO stop collecting events */
		if (IS_ENABLED(CONFIG_ACCEL_FIFO))
			enable_fifo(s, 0);
		ret = disable_reg_bits(s, BMI260_PWR_CTRL,
				       BMI260_PWR_EN(s->type));
		ret = disable_reg_bits(s, BMI260_CONF_REG(s->type),
				       BMI260_FILTER_PERF);
		msleep(3);
		data->odr = 0;
#ifdef CONFIG_MAG_BMI260_BMM150
		if (s->type == MOTIONSENSE_TYPE_MAG)
			moc->batch_size = 0;
#endif
		return ret;
	} else if (data->odr == 0) {
		enable_reg_bits(s, BMI260_PWR_CTRL,
				BMI260_PWR_EN(s->type));
		enable_reg_bits(s, BMI260_CONF_REG(s->type),
				BMI260_FILTER_PERF);
		/* TODO(chingkang): check if wakeup_time is correct */
		msleep(wakeup_time[s->type]);
	}

	ctrl_reg = BMI260_CONF_REG(s->type);
	reg_val = BMI260_ODR_TO_REG(rate);
	normalized_rate = BMI260_REG_TO_ODR(reg_val);
	if (rnd && (normalized_rate < rate)) {
		reg_val++;
		normalized_rate = BMI260_REG_TO_ODR(reg_val);
	}

	switch (s->type) {
	case MOTIONSENSE_TYPE_ACCEL:
		if (normalized_rate > BMI260_ACCEL_MAX_FREQ ||
			normalized_rate < BMI260_ACCEL_MIN_FREQ)
			return EC_RES_INVALID_PARAM;
		break;
	case MOTIONSENSE_TYPE_GYRO:
		if (normalized_rate > BMI260_GYRO_MAX_FREQ ||
			normalized_rate < BMI260_GYRO_MIN_FREQ)
			return EC_RES_INVALID_PARAM;
		break;
#ifdef CONFIG_MAG_BMI260_BMM150
	case MOTIONSENSE_TYPE_MAG:
		/* We use the regular preset we can go about 100Hz */
		if (reg_val > BMI260_ODR_100HZ || reg_val < BMI260_ODR_0_78HZ)
			return EC_RES_INVALID_PARAM;
		break;
#endif

	default:
		return EC_RES_INVALID_PARAM;
	}

	/*
	 * Lock accel resource to prevent another task from attempting
	 * to write accel parameters until we are done.
	 */
	mutex_lock(s->mutex);

	ret = raw_read8(s->port, s->i2c_spi_addr_flags, ctrl_reg, &val);
	if (ret != EC_SUCCESS)
		goto accel_cleanup;

	val = (val & ~BMI260_ODR_MASK) | reg_val;
	ret = raw_write8(s->port, s->i2c_spi_addr_flags, ctrl_reg, val);
	if (ret != EC_SUCCESS)
		goto accel_cleanup;

	/* Now that we have set the odr, update the driver's value. */
	data->odr = normalized_rate;

#ifdef CONFIG_MAG_BMI260_BMM150
	if (s->type == MOTIONSENSE_TYPE_MAG) {
		/* Reset the calibration */
		init_mag_cal(moc);
		/*
		 * We need at least MIN_BATCH_SIZE amd we must have collected
		 * for at least MIN_BATCH_WINDOW_US.
		 * Given odr is in mHz, multiply by 1000x
		 */
		moc->batch_size = MAX(
			MAG_CAL_MIN_BATCH_SIZE,
			(data->odr * 1000) / (MAG_CAL_MIN_BATCH_WINDOW_US));
		CPRINTS("Batch size: %d", moc->batch_size);
	}
#endif

	/*
	 * FIFO start collecting events.
	 * They will be discarded if AP does not want them.
	 */
	if (IS_ENABLED(CONFIG_ACCEL_FIFO))
		enable_fifo(s, 1);

accel_cleanup:
	mutex_unlock(s->mutex);
	return ret;
}

