static int enable_fifo(const struct motion_sensor_t *s, int enable)
{
	struct bmi260_drv_data_t *data = BMI260_GET_DATA(s);
	int ret;

	if (enable) {
		/* FIFO start collecting events */
		ret = enable_reg_bits(s, BMI260_FIFO_CONFIG_1,
				      BMI260_FIFO_SENSOR_EN(s->type));
		if (ret == EC_SUCCESS)
			data->flags |= 1 << (s->type + BMI260_FIFO_FLAG_OFFSET);

	} else {
		/* FIFO stop collecting events */
		ret = disable_reg_bits(s, BMI260_FIFO_CONFIG_1,
				       BMI260_FIFO_SENSOR_EN(s->type));
		if (ret == EC_SUCCESS)
			data->flags &=
				~(1 << (s->type + BMI260_FIFO_FLAG_OFFSET));
	}
	return ret;
}

static int set_range(const struct motion_sensor_t *s,
				int range,
				int rnd)
{
	int ret, range_tbl_size;
	uint8_t reg_val, ctrl_reg;
	const struct accel_param_pair *ranges;
	struct accelgyro_saved_data_t *data = BMI260_GET_SAVED_DATA(s);

	if (s->type == MOTIONSENSE_TYPE_MAG) {
		data->range = range;
		return EC_SUCCESS;
	}

	ctrl_reg = BMI260_RANGE_REG(s->type);
	ranges = get_range_table(s->type, &range_tbl_size);
	reg_val = get_reg_val(range, rnd, ranges, range_tbl_size);

	ret = raw_write8(s->port, s->i2c_spi_addr_flags,
			 ctrl_reg, reg_val);
	/* Now that we have set the range, update the driver's value. */
	if (ret == EC_SUCCESS)
		data->range = get_engineering_val(reg_val, ranges,
				range_tbl_size);
	return ret;
}

