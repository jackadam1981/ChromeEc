#ifdef CONFIG_ACCEL_INTERRUPTS

enum fifo_state {
	FIFO_HEADER,
	FIFO_DATA_SKIP,
	FIFO_DATA_TIME,
	FIFO_DATA_CONFIG,
};


#define BMI260_FIFO_BUFFER 64
static uint8_t bmi260_buffer[BMI260_FIFO_BUFFER];
/*
 * Decode the header from the fifo.
 * Return 0 if we need further processing.
 * Sensor mutex must be held during processing, to protect the fifos.
 *
 * @s: base sensor
 * @hdr: the header to decode
 * @bp: current pointer in the buffer, updated when processing the header.
 * @ep: pointer to the end of the valid data in the buffer.
 */
static int bmi260_decode_header(struct motion_sensor_t *accel,
		enum fifo_header hdr, uint32_t last_ts,
		uint8_t **bp, uint8_t *ep)
{
	if ((hdr & BMI260_FH_MODE_MASK) == BMI260_EMPTY &&
			(hdr & BMI260_FH_PARM_MASK) != 0) {
		int i, size = 0;
		/* Check if there is enough space for the data frame */
		for (i = MOTIONSENSE_TYPE_MAG; i >= MOTIONSENSE_TYPE_ACCEL;
		     i--) {
			if (hdr & (1 << (i + BMI260_FH_PARM_OFFSET)))
				size += (i == MOTIONSENSE_TYPE_MAG ? 8 : 6);
		}
		if (*bp + size > ep) {
			/* frame is not complete, it will be retransmitted. */
			*bp = ep;
			return 1;
		}
		for (i = MOTIONSENSE_TYPE_MAG; i >= MOTIONSENSE_TYPE_ACCEL;
			 i--) {
			struct motion_sensor_t *s = accel + i;

			if (hdr & (1 << (i + BMI260_FH_PARM_OFFSET))) {
				struct ec_response_motion_sensor_data vector;
				int *v = s->raw_xyz;
				vector.flags = 0;
				normalize(s, v, *bp);
				if (IS_ENABLED(CONFIG_ACCEL_SPOOF_MODE) &&
					s->flags & MOTIONSENSE_FLAG_IN_SPOOF_MODE)
					v = s->spoof_xyz;
				vector.data[X] = v[X];
				vector.data[Y] = v[Y];
				vector.data[Z] = v[Z];
				vector.sensor_num = s - motion_sensors;
				motion_sense_fifo_stage_data(&vector, s, 3,
						last_ts);
				*bp += (i == MOTIONSENSE_TYPE_MAG ? 8 : 6);
			}
		}
		return 1;
	} else {
		return 0;
	}
}



/**
 * Retrieve hardware FIFO from sensor,
 * - put data in Sensor Hub fifo.
 * - update sensor raw_xyz vector with the last information.
 * We put raw data in hub fifo and process data from there.
 * @s Pointer to sensor data.
 *
 * Read only up to  bmi260_buffer. If more reads are needed, we will be called
 * again by the interrupt routine.
 *
 * NOTE: If a new driver supports this function, be sure to add a check
 * for spoof_mode in order to load the sensor stack with the spoofed
 * data.  See accelgyro_bmi260.c::load_fifo for an example.
 */
static int load_fifo(struct motion_sensor_t *s, uint32_t last_ts)
{
	struct bmi260_drv_data_t *data = BMI260_GET_DATA(s);
	uint16_t length;
	enum fifo_state state = FIFO_HEADER;
	uint8_t *bp = bmi260_buffer;
	uint8_t *ep;
	uint32_t beginning;

	if (s->type != MOTIONSENSE_TYPE_ACCEL)
		return EC_SUCCESS;

	if (!(data->flags &
	     (BMI260_FIFO_ALL_MASK << BMI260_FIFO_FLAG_OFFSET))) {
		/*
		 * The FIFO was disabled while we were processing it.
		 *
		 * Flush potential left over:
		 * When sensor is resumed, we won't read old data.
		 */
		raw_write8(s->port, s->i2c_spi_addr_flags,
			   BMI260_CMD_REG, BMI260_CMD_FIFO_FLUSH);
		return EC_SUCCESS;
	}

	raw_read_n(s->port, s->i2c_spi_addr_flags,
		   BMI260_FIFO_LENGTH_0,
		   (uint8_t *)&length, sizeof(length));
	length &= BMI260_FIFO_LENGTH_MASK;

	/*
	 * We have not requested timestamp, no extra frame to read.
	 * if we have too much to read, read the whole buffer.
	 */
	if (length == 0) {
		/* TODO(chingkang): check why this happen often */
		CPRINTS("unexpected empty FIFO");
		return EC_SUCCESS;
	}

	/* Add one byte to get an empty FIFO frame.*/
	length++;

	if (length > sizeof(bmi260_buffer))
		CPRINTS("unexpected large FIFO: %d", length);
	length = MIN(length, sizeof(bmi260_buffer));


	raw_read_n(s->port, s->i2c_spi_addr_flags,
		   BMI260_FIFO_DATA, bmi260_buffer, length);
	beginning = *(uint32_t *)bmi260_buffer;
	ep = bmi260_buffer + length;
	/*
	 * FIFO is invalid when reading while the sensors are all
	 * suspended.
	 * Instead of returning the empty frame, it can return a
	 * pattern that looks like a valid header: 84 or 40.
	 * If we see those, assume the sensors have been disabled
	 * while this thread was running.
	 */
	if (beginning == 0x84848484 ||
			(beginning & 0xdcdcdcdc) == 0x40404040) {
		CPRINTS("Suspended FIFO: accel ODR/rate: %d/%d: 0x%08x",
				BASE_ODR(s->config[SENSOR_CONFIG_AP].odr),
				get_data_rate(s),
				beginning);
		return EC_SUCCESS;
	}

	while (bp < ep) {
		switch (state) {
		case FIFO_HEADER: {
			enum fifo_header hdr = *bp++;

			if (bmi260_decode_header(s, hdr, last_ts, &bp, ep))
				continue;
			/* Other cases */
			hdr &= 0xdc;
			switch (hdr) {
			case BMI260_EMPTY:
				return EC_SUCCESS;
			case BMI260_SKIP:
				state = FIFO_DATA_SKIP;
				break;
			case BMI260_TIME:
				state = FIFO_DATA_TIME;
				break;
			case BMI260_CONFIG:
				state = FIFO_DATA_CONFIG;
				break;
			default:
				CPRINTS("Unknown header: 0x%02x @ %zd",
						hdr, bp - bmi260_buffer);
				raw_write8(s->port, s->i2c_spi_addr_flags,
						BMI260_CMD_REG,
						BMI260_CMD_FIFO_FLUSH);
				return EC_ERROR_NOT_HANDLED;
			}
			break;
		}
		case FIFO_DATA_SKIP:
			CPRINTS("@ %zd - %d, skipped %d frames",
					bp - bmi260_buffer, length, *bp);
			bp++;
			state = FIFO_HEADER;
			break;
		case FIFO_DATA_CONFIG:
			CPRINTS("@ %zd - %d, config change: 0x%02x",
					bp - bmi260_buffer, length, *bp);
			bp++;
			state = FIFO_HEADER;
			break;
		case FIFO_DATA_TIME:
			if (bp + 3 > ep) {
				bp = ep;
				continue;
			}
			/* We are not requesting timestamp */
			CPRINTS("timestamp %d", (bp[2] << 16) |
					(bp[1] << 8) | bp[0]);
			state = FIFO_HEADER;
			bp += 3;
			break;
		default:
			CPRINTS("Unknown data: 0x%02x", *bp++);
			state = FIFO_HEADER;
		}
	}

	return EC_SUCCESS;
}

/**
 * bmi260_interrupt - called when the sensor activates the interrupt line.
 *
 * This is a "top half" interrupt handler, it just asks motion sense ask
 * to schedule the "bottom half", ->irq_handler().
 */
void bmi260_interrupt(enum gpio_signal signal)
{
	if (IS_ENABLED(CONFIG_ACCEL_FIFO))
		last_interrupt_timestamp = __hw_clock_source_read();

	task_set_event(TASK_ID_MOTIONSENSE,
		       CONFIG_ACCELGYRO_BMI260_INT_EVENT, 0);
}


static int config_interrupt(const struct motion_sensor_t *s)
{
	int ret, tmp;

	if (s->type != MOTIONSENSE_TYPE_ACCEL)
		return EC_SUCCESS;

	mutex_lock(s->mutex);
	raw_write8(s->port, s->i2c_spi_addr_flags,
		   BMI260_CMD_REG, BMI260_CMD_FIFO_FLUSH);
/*  TODO(henryhsu): check 260 how to reset interrupt status */
/*  raw_write8(s->port, s->i2c_spi_addr_flags,*/
/*       BMI260_CMD_REG, BMI260_CMD_INT_RESET);*/

#ifdef CONFIG_GESTURE_SENSOR_DOUBLE_TAP
	/* interrupt default is set to INT_D */
	raw_write8(s->port, s->i2c_spi_addr_flags,
		   BMI260_FEAT_PAGE, 1);
	raw_read16(s->port, s->i2c_spi_addr_flags,
		   BMI260_TAP_1, &tmp);
	val &= ~BMI260_TAP_1_SENSITIVITY_MASK;
	val |= BMI260_TAP_1_EN;
	raw_write16(s->port, s->i2c_spi_addr_flags,
		   BMI260_TAP_1, tmp);

#endif
#ifdef CONFIG_BMI260_ORIENTATION_SENSOR
	/* only use orientation sensor on the lid sensor */
	/* TODO(henryhsu): need to know how to calculate hysteresis (0x32) feature page 2 */
	if (s->location == MOTIONSENSE_LOC_LID) {
		raw_write8(s->port, s->i2c_spi_addr_flags,
			   BMI260_FEAT_PAGE, 1);
		raw_reade16(s->port, s->i2c_spi_addr_flags,
			     BMI260_ORIENT_1, &tmp);
		val |= BMI260_ORIENT_1_EN;
		val &= ~BMI260_ORIENT_1_UD_EN;
		val &= ~BMI260_ORIENT_1_MODE_MASK;
		raw_write16(s->port, s->i2c_spi_addr_flags,
			    BMI260_ORIENT_1, tmp);
	}
#endif

	/* TODO(chingkang): BMI260 only have not/permanent latch mode
	ret = raw_write8(s->port, s->i2c_spi_addr_flags,
	BMI260_INT_LATCH, BMI260_INT_LATCH_EN);
	*/

	/* configure int1 as an interrupt */
	ret = raw_write8(s->port, s->i2c_spi_addr_flags,
			 BMI260_INT1_IO_CTRL,
			 BMI260_INT1_OUTPUT_EN);
#ifndef CONFIG_ACCELGYRO_BMI260_INT2_OUTPUT
	/* configure int2 as an external input. */
	ret = raw_write8(s->port, s->i2c_spi_addr_flags,
			 BMI260_INT2_IO_CTRL,
			 BMI260_INT2_INPUT_EN);
#endif

	/* Map activity interrupt to int 1 */
	tmp = 0;
#ifdef CONFIG_GESTURE_SIGMO
	tmp |= BMI260_MAP_ANY_MOTION_OUT;
#endif
#ifdef CONFIG_GESTURE_SENSOR_DOUBLE_TAP
	tmp |= BMI260_MAP_TAP_OUT;
#endif
#ifdef CONFIG_BMI260_ORIENTATION_SENSOR
	/* enable orientation interrupt for lid sensor only */
	if (s->location == MOTIONSENSE_LOC_LID)
		tmp |= BMI260_MAP_ORIENTATION_OUT;
#endif
	ret = raw_write8(s->port, s->i2c_spi_addr_flags,
			 BMI260_INT1_MAP_FEAT, tmp);

	if (IS_ENABLED(CONFIG_ACCEL_FIFO)) {
		/* map fifo water mark to int 1 */
		ret = raw_write8(s->port, s->i2c_spi_addr_flags,
				 BMI260_INT_MAP_DATA,
				 BMI260_INT_MAP_DATA_REG(1, FWM) |
				 BMI260_INT_MAP_DATA_REG(1, FFULL));

		/*
		 * Configure fifo watermark to int whenever there's any data in
		 * there
		 */
		ret = raw_write8(s->port, s->i2c_spi_addr_flags,
				 BMI260_FIFO_WTM_0, 1);
		ret = raw_write8(s->port, s->i2c_spi_addr_flags,
				 BMI260_FIFO_WTM_1, 0);
#ifdef CONFIG_ACCELGYRO_BMI260_INT2_OUTPUT
		ret = raw_write8(s->port, s->i2c_spi_addr_flags,
				 BMI260_FIFO_CONFIG_1,
				 BMI260_FIFO_HEADER_EN);
#else
		ret = raw_write8(s->port, s->i2c_spi_addr_flags,
				 BMI260_FIFO_CONFIG_1,
				 (BMI260_FIFO_TAG_INT_LEVEL << BMI260_FIFO_TAG_INT2_EN_OFFSET) |
				 BMI260_FIFO_HEADER_EN);
#endif

		/* Set fifo */
		/* TODO(chingkang): 260 don't have this setting */
		/*ret = raw_read8(s->port, s->i2c_spi_addr_flags,*/
				/*BMI260_INT_EN_1, &tmp);*/
		/*tmp |= BMI260_INT_FWM_EN | BMI260_INT_FFUL_EN;*/
		/*ret = raw_write8(s->port, s->i2c_spi_addr_flags,*/
				 /*BMI260_INT_EN_1, tmp);*/
	}
	mutex_unlock(s->mutex);
	return ret;
}

#ifdef CONFIG_BMI260_ORIENTATION_SENSOR
static void irq_set_orientation(struct motion_sensor_t *s)
{
	int new_orientation;
	/* read orientation */
	raw_write8(s->port, s->i2c_spi_addr_flags,
		   BMI260_FEAT_PAGE, 0);
	raw_read8(s->port, s->i2c_spi_addr_flags,
		  BMI260_ORIENT_OUT, &new_orientation);

	if (BMI260_GET_DATA(s)->raw_orientation != new_orientation) {
		enum motionsensor_orientation orientation =
			MOTIONSENSE_ORIENTATION_UNKNOWN;

		BMI260_GET_DATA(s)->raw_orientation =
			new_orientation;

		switch (new_orientation) {
		case BMI260_ORIENT_PORTRAIT:
			orientation = MOTIONSENSE_ORIENTATION_PORTRAIT;
			break;
		case BMI260_ORIENT_PORTRAIT_INVERT:
			orientation =
				MOTIONSENSE_ORIENTATION_UPSIDE_DOWN_PORTRAIT;
			break;
		case BMI260_ORIENT_LANDSCAPE:
			orientation = MOTIONSENSE_ORIENTATION_LANDSCAPE;
			break;
		case BMI260_ORIENT_LANDSCAPE_INVERT:
			orientation =
				MOTIONSENSE_ORIENTATION_UPSIDE_DOWN_LANDSCAPE;
			break;
		default:
			break;
		}
		orientation = motion_sense_remap_orientation(s, orientation);
		SET_ORIENTATION(s, orientation);
	}
}
#endif

/**
 * irq_handler - bottom half of the interrupt stack.
 * Ran from the motion_sense task, finds the events that raised the interrupt.
 *
 * For now, we just print out. We should set a bitmask motion sense code will
 * act upon.
 */
static int irq_handler(struct motion_sensor_t *s, uint32_t *event)
{
	/* use uint16_t interrupt can cause error. */
	uint32_t interrupt = 0;
	int8_t has_read_fifo = 0;
	int rv;

	if ((s->type != MOTIONSENSE_TYPE_ACCEL) ||
			(!(*event & CONFIG_ACCELGYRO_BMI260_INT_EVENT)))
		return EC_ERROR_NOT_HANDLED;

	do {
		rv = raw_read16(s->port, s->i2c_spi_addr_flags,
				BMI260_INT_STATUS_0, (uint16_t *)&interrupt);
		/*
		 * Bail out of this loop there was an error reading the register
		 */
		if (rv)
			return rv;

#ifdef CONFIG_GESTURE_SENSOR_DOUBLE_TAP
		if (interrupt & BMI260_TAP_OUT)
			*event |= TASK_EVENT_MOTION_ACTIVITY_INTERRUPT(
					MOTIONSENSE_ACTIVITY_DOUBLE_TAP);
#endif
#ifdef CONFIG_GESTURE_SIGMO
		if (interrupt & BMI260_SIG_MOTION_OUT)
			*event |= TASK_EVENT_MOTION_ACTIVITY_INTERRUPT(
					MOTIONSENSE_ACTIVITY_SIG_MOTION);
#endif
		if (IS_ENABLED(CONFIG_ACCEL_FIFO) &&
			interrupt & (BMI260_FWM_INT | BMI260_FFULL_INT)) {
			load_fifo(s, last_interrupt_timestamp);
			has_read_fifo = 1;
		}
#ifdef CONFIG_BMI260_ORIENTATION_SENSOR
		if (interrupt & BMI260_ORIENTATION_OUT)
			irq_set_orientation(s);
#endif
	} while (interrupt != 0);

	if (IS_ENABLED(CONFIG_ACCEL_FIFO) && has_read_fifo)
		motion_sense_fifo_commit_data();

	return EC_SUCCESS;
}
#endif  /* CONFIG_ACCEL_INTERRUPTS */


/* TODO(chingkang) */
static int read(const struct motion_sensor_t *s, intv3_t v)
{
	uint8_t data[6];
	int ret, status = 0;

	ret = raw_read8(s->port, s->i2c_spi_addr_flags,
			BMI260_STATUS, &status);
	if (ret != EC_SUCCESS)
		return ret;

	/*
	 * If sensor data is not ready, return the previous read data.
	 * Note: return success so that motion senor task can read again
	 * to get the latest updated sensor data quickly.
	 */
	if (!(status & BMI260_DRDY_MASK(s->type))) {
		if (v != s->raw_xyz)
			memcpy(v, s->raw_xyz, sizeof(s->raw_xyz));
		return EC_SUCCESS;
	}

	/* Read 6 bytes starting at xyz_reg */
	ret = raw_read_n(s->port, s->i2c_spi_addr_flags,
			 get_xyz_reg(s->type), data, 6);

	if (ret != EC_SUCCESS) {
		CPRINTS("%s: type:0x%X RD XYZ Error %d", s->name, s->type, ret);
		return ret;
	}
	normalize(s, v, data);
	return EC_SUCCESS;
}

