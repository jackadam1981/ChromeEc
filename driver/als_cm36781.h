#ifndef __CROS_EC_ALS_CM36781_H
#define __CROS_EC_ALS_CM36781_H

/* I2C interface */
#define CM36781_I2C_ADDR (0x51 | I2C_FLAG_BIG_ENDIAN)

// CM36781 registers
#define CM36781_ALS_CONF 0x00
#define CM36781_ALS_THDH 0x01
#define CM36781_ALS_THDL 0x02
#define CM36781_PS_CONF1 0x03
#define CM36781_PS_CONF3 0x04
#define CM36781_PS_CANC 0x05
#define CM36781_PS_THDL 0x06
#define CM36781_PS_THDH 0x07
#define CM36781_PS_DATA 0x08
#define CM36781_ALS_DATA 0x09
#define CM36781_WHITE_DATA 0x0A
#define CM36781_INT_FLAG 0x0D
#define CM36781_ID 0x0E

// CM36781 ALS_CONF register bits
#define CM36781_ALS_SD 0x0001
#define CM36781_ALS_INT_EN 0x0002
#define CM36781_ALS_PERS_1 0x0000
#define CM36781_ALS_PERS_2 0x0004
#define CM36781_ALS_PERS_4 0x0008
#define CM36781_ALS_PERS_8 0x000C
#define CM36781_ALS_IT_MASK 0x00C0
#define CM36781_ALS_IT_50MS 0x0000
#define CM36781_ALS_IT_100MS 0x0040
#define CM36781_ALS_IT_200MS 0x0080
#define CM36781_ALS_IT_400MS 0x00C0
#define CM36781_ALS_CONF_DEFAULT (CM36781_ALS_PERS_2 | CM36781_ALS_IT_50MS)

// CM36781 PS_CONF1 register bits
#define CM36781_PS_SD 0x0001
#define CM36781_PS_IT_1T 0x0000
#define CM36781_PS_IT_1_5T 0x0002
#define CM36781_PS_IT_2T 0x0004
#define CM36781_PS_IT_4T 0x0006
#define CM36781_PS_IT_8T 0x0008
#define CM36781_PS_IT_9T 0x000A
#define CM36781_PS_PERS_1 0x0000
#define CM36781_PS_PERS_2 0x0010
#define CM36781_PS_PERS_3 0x0020
#define CM36781_PS_PERS_4 0x0030
#define CM36781_PS_DUTY_1_160 0x0000
#define CM36781_PS_DUTY_1_320 0x0040
#define CM36781_PS_DUTY_1_640 0x0080
#define CM36781_PS_DUTY_1_1280 0x00C0
#define CM36781_PS_INT_EN 0x0300
#define CM36781_PS_CONF1_DEFAULT \
	(CM36781_PS_IT_8T | CM36781_PS_PERS_2 | CM36781_PS_DUTY_1_160)

// CM36781 PS_CONF3 register bits
#define CM36781_PS_FOR_TRIG_ONCE 0x0004
#define CM36781_PS_FOR_EN 0x0008
#define CM36781_PS_SMART_PERS_EN 0x0010
#define CM36781_PS_MPS_1 0x0000
#define CM36781_PS_MPS_2 0x0020
#define CM36781_PS_MPS_4 0x0040
#define CM36781_PS_MPS_8 0x0060
#define CM36781_PS_LED_I_50MA 0x0000
#define CM36781_PS_LED_I_75MA 0x0100
#define CM36781_PS_LED_I_100MA 0x0200
#define CM36781_PS_LED_I_120MA 0x0300
#define CM36781_PS_LED_I_140MA 0x0400
#define CM36781_PS_LED_I_160MA 0x0500
#define CM36781_PS_LED_I_180MA 0x0600
#define CM36781_PS_LED_I_200MA 0x0700
#define CM36781_PS_DLO_MODE_EN 0x2000
#define CM36781_PS_CONF3_DEFAULT (CM36781_PS_MPS_8 | CM36781_PS_LED_I_50MA)

// CM36781 INT_FLAG register bits
#define CM36781_PS_IF_AWAY 0x0100
#define CM36781_PS_IF_CLOSE 0x0200
#define CM36781_ALS_IF_H 0x1000
#define CM36781_ALS_IF_L 0x2000

// CM36781 device ID
#define CM36781_DEV_ID 0x58

extern const struct accelgyro_drv cm36781_drv;

#endif /* __CROS_EC_ALS_CM36781_H */
