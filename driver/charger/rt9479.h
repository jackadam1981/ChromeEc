#define BITS_SET_RANGE(lsb, msb) (((1U << ((msb) - (lsb) + 1)) - 1) << (lsb))

#define REG_FIELD_GET(reg, lsb, msb) \
	(((reg) >> (lsb)) & (uint32_t)((1 << ((msb) - (lsb) + 1)) - 1))

