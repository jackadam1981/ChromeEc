#define REG_MIN_SYSTEM_VOLTAGE BQ24800_MIN_SYSTEM_VOLTAGE
#define REG_INPUT_CURRENT BQ24800_INPUT_CURRENT
#define REG_MANUFACTURE_ID BQ24800_MANUFACTURE_ID
