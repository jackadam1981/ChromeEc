#define REG_PROCHOT_OPTION1 BQ24773_PROCHOT_OPTION1
#define REG_CHARGE_CURRENT BQ24773_CHARGE_CURRENT
#define REG_MAX_CHARGE_VOLTAGE BQ24773_MAX_CHARGE_VOLTAGE
