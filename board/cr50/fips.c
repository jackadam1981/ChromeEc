/**
 * Combined FIPS status & global error.
 * default value is  = FIPS_UNINITIALIZED
 */
static enum fips_status _fips_status;

/**
 * Set status of FIPS power-up tests.
 *
 * @param asserted: 0 power-up tests should run on resume, otherwise can be
 * skipped
 */
static void set_board_fips_test(int asserted)
{
	/* Enable writing to the long life register */
	GWRITE_FIELD(PMU, LONG_LIFE_SCRATCH_WR_EN, REG1, 1);

	if (asserted) {
		GREG32(PMU, LONG_LIFE_SCRATCH1) |= BOARD_FIPS_POWERUP_DONE;
		_fips_status |= FIPS_POWER_UP_TEST_DONE;
	} else {
		GREG32(PMU, LONG_LIFE_SCRATCH1) &= ~BOARD_FIPS_POWERUP_DONE;
		_fips_status &= ~FIPS_POWER_UP_TEST_DONE;
	}
	/* Disable writing to the long life register */
	GWRITE_FIELD(PMU, LONG_LIFE_SCRATCH_WR_EN, REG1, 0);
}

/* Nvmem variable name for FIPS config */
static const uint8_t k_fips_config = NVMEM_VAR_FIPS_CONFIG;
static void set_board_fips(uint8_t asserted)
{
	setvar(&k_fips_config, sizeof(k_fips_config), &asserted,
	       sizeof(asserted));
}

static int get_board_fips(void)
{
	const struct tuple *t;

	t = getvar(&k_fips_config, sizeof(k_fips_config));
	return (t) ? tuple_val(t)[0] : 0;
}

void fips_set_status(enum fips_status status)
{
	/**
	 * if FIPS error took place, drop indication of FIPS approved mode.
	 * Next cycle of sleep will power-cycle HW crypto components, so any
	 * soft-errors will be recovered. In case of hard errors it
	 * will be detected again.
	 */
	if (status & FIPS_ERROR_MASK)
		set_board_fips_test(0);

	/* accumulate status */
	_fips_status |= status;
}

enum fips_status fips_status(void)
{
	return _fips_status;
}

int fips_mode(void)
{
	return (_fips_status & FIPS_MODE_REQUESTED);
}

int fips_crypto_allowed(void)
{
	/**
	 * we can run crypto if either FIPS approved mode is not requested or
	 * when it's properly initialized and not in error state.
	 */
	return (!(_fips_status & FIPS_MODE_REQUESTED) ||
		((_fips_status & FIPS_MODE_REQUESTED) &&
		 (_fips_status & FIPS_POWER_UP_TEST_DONE) &&
		 !(_fips_status & FIPS_ERROR_MASK)));
}

void _fips_throw_err(enum fips_status err, const char *func, int line)
{
	fips_set_status(err);
	if (_fips_status & FIPS_ERROR_MASK)
		ccprints("%s:%d fips err 0x%08x", func, line, _fips_status);
}


