static void mp2964_on_startup(void)
{
	static int chip_updated;
	int status;

	if (chip_updated)
		return;

	chip_updated = 1;

	status = mp2964_tune(mp2964_page0, ARRAY_SIZE(mp2964_page0),
			     mp2964_page1, ARRAY_SIZE(mp2964_page1));

	if (status == EC_SUCCESS)
		CPRINTS("%s: PMIC update done", __func__);
	else
		CPRINTS("%s: could not update all settings", __func__);
}
DECLARE_HOOK(HOOK_CHIPSET_STARTUP, mp2964_on_startup, HOOK_PRIO_DEFAULT);
