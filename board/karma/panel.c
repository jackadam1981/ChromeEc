static int get_panel_id(void)
{
	int pin_status = 0;

	if (gpio_get_level(GPIO_PANEL_ID_0))
		pin_status |= 0x01;
	if (gpio_get_level(GPIO_PANEL_ID_1))
		pin_status |= 0x02;
	if (gpio_get_level(GPIO_PANEL_ID_2))
		pin_status |= 0x04;

	CPRINTS("Panel pin_status 0x%X", pin_status);

	switch (pin_status) {
	case 0x04:
		return PANEL_LM_SSE2;
	case 0x05:
		return PANEL_LM_SSK1;
	default:
		return PANEL_UNKNOWN;
	}
}

static void flash_edid(void)
{
	int i, j, rv, data_is_different;
	int panel_id = get_panel_id();
	uint8_t edid_tmp[EEPROM_PAGE_SIZE];

	if (panel_id == PANEL_UNKNOWN) {
		CPRINTS("Panel ID unknown!");
		return;
	}

	for (i = 0; i < EEPROM_TOTAL_SIZE / EEPROM_PAGE_SIZE; ++i) {
		/* Read EDID from EEPROM to verify. */
		rv = i2c_read_block(
			I2C_PORT_THERMAL,
			I2C_ADDR_EEPROM,
			i * EEPROM_PAGE_SIZE,
			edid_tmp,
			EEPROM_PAGE_SIZE);

		/* Time interval between pages. */
		task_wait_event(5 * MSEC);

		if (rv) {
			data_is_different = 1;
			CPRINTS("Read EDID from EEPROM, page %d FAILED!", i);
		} else {
			data_is_different = 0;

			/* Verify EDID. */
			for (j = 0; j < EEPROM_PAGE_SIZE; ++j) {
				if (edid_tmp[j] !=
				    edid[panel_id][i * EEPROM_PAGE_SIZE + j]) {
					data_is_different = 1;
					break;
				}
			}
		}

		/* If data is already correct, no need to write again. */
		if (!data_is_different)
			continue;

		/* If data is not correct, Write EDID into EEPROM. */
		rv = i2c_write_block(
			I2C_PORT_THERMAL,
			I2C_ADDR_EEPROM,
			i * EEPROM_PAGE_SIZE,
			(uint8_t *)&edid[panel_id][i*EEPROM_PAGE_SIZE],
			EEPROM_PAGE_SIZE);

		/* Time interval between pages. */
		task_wait_event(5 * MSEC);

		if (rv)
			CPRINTS("Write EDID into EEPROM, page %d FAILED!", i);
	}
}
