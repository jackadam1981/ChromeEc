static void flash_edid(void)
{
	int i, j, rv, data_is_different;
	uint8_t edid_tmp[EEPROM_PAGE_SIZE];

	for (i = 0; i < EEPROM_TOTAL_SIZE / EEPROM_PAGE_SIZE; ++i) {
		/* Read EDID from EEPROM to verify. */
		rv = i2c_read_block(
			I2C_PORT_THERMAL,
			I2C_ADDR_EEPROM,
			i * EEPROM_PAGE_SIZE,
			edid_tmp,
			EEPROM_PAGE_SIZE);

		/* Time interval between pages. */
		task_wait_event(5 * MSEC);

		if (rv) {
			data_is_different = 1;
			CPRINTS("Read EDID from EEPROM, page %d FAILED!", i);
		} else {
			data_is_different = 0;

			/* Verify EDID. */
			for (j = 0; j < EEPROM_PAGE_SIZE; ++j) {
				if (edid_tmp[j] !=
					edid[i * EEPROM_PAGE_SIZE + j]) {
					data_is_different = 1;
					break;
				}
			}
		}

		/* If data is already correct, no need to write again. */
		if (!data_is_different)
			continue;

		/* If data is not correct, Write EDID into EEPROM. */
		rv = i2c_write_block(
			I2C_PORT_THERMAL,
			I2C_ADDR_EEPROM,
			i * EEPROM_PAGE_SIZE,
			(uint8_t *)&edid[i*EEPROM_PAGE_SIZE],
			EEPROM_PAGE_SIZE);

		/* Time interval between pages. */
		task_wait_event(5 * MSEC);

		if (rv)
			CPRINTS("Write EDID into EEPROM, page %d FAILED!", i);
	}
}
DECLARE_HOOK(HOOK_INIT, flash_edid, HOOK_PRIO_DEFAULT);
