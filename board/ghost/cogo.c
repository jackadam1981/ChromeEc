void cogo_task(void *u)
{
	const uint8_t *anim_data;
	unsigned int anim_points;
	unsigned int step;
	timestamp_t ts_now = get_time();
	timestamp_t ts_next = { .val = 0 };

	pwm_set_duty(PWM_CH_COGO, 0);
	pwm_enable(PWM_CH_COGO, 1);
	gpio_set_level(GPIO_GLOGO_EN, 1);

	/* ramp up signal */

	anim_data = v_ramp_up_120;
	anim_points = ARRAY_SIZE(v_ramp_up_120);

	step = 0;
	do {
		ts_now = get_time();
		if (ts_now.val < ts_next.val) {
			usleep(ts_next.val - ts_now.val);
			continue;
		}
		ts_next.val = ts_now.val + COGO_TICK_INTERVAL_US;

		pwm_set_duty(PWM_CH_COGO, anim_data[step]);
		step = (step + 1) % anim_points;
	} while (step != 0);

	/* output wave forever */

	anim_data = v_cosine_240;
	anim_points = ARRAY_SIZE(v_cosine_240);

	step = 0;
	while (1) {
		ts_now = get_time();
		if (ts_now.val < ts_next.val) {
			usleep(ts_next.val - ts_now.val);
			continue;
		}
		ts_next.val = ts_now.val + COGO_TICK_INTERVAL_US;

		pwm_set_raw_duty(PWM_CH_COGO,
				 (anim_data[step] * EC_PWM_MAX_DUTY) /
				 UINT8_MAX);
		step = (step + 1) % anim_points;
	}
}
