static void mp2964_on_startup(void)
{
	int status;

	ccprintf("%s: attempting to tune PMIC\n", __func__);

	if (0) {
		status = mp2964_tune(rail_a_rev3, ARRAY_SIZE(rail_a_rev3),
			     rail_b_rev3, ARRAY_SIZE(rail_b_rev3));
	} else {
		status = mp2964_tune(rail_a_rev4, ARRAY_SIZE(rail_a_rev4),
			     rail_b_rev4, ARRAY_SIZE(rail_b_rev4));
	}
	if (status != EC_SUCCESS)
		ccprintf("%s: could not update all settings\n", __func__);
}

DECLARE_HOOK(HOOK_CHIPSET_STARTUP, mp2964_on_startup,
	     HOOK_PRIO_FIRST);
